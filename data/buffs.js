//  強化・弱体 (バフ・デバフ。コードではまとめて buff と呼ぶ) の種類と、その表示 (アイコン)
//  どれも、戦うキャラならだれにでも (主人公・敵・仲間) かけられる (src/units.js の addBuff)
//  今かける手段は、自分を強化する技だけ: data/player.js の skills に type: 'buff' で書く (どれをかけるか・何行動続くか)
//  (道具の効果 { kind: 'addBuff', buff, actions } でもかけられる。data/items.js の consumables。今の道具には使っていない)
// =====================================================================
//
//   name   : 表示名 (メッセージ欄・アイコンにマウスを重ねたときの説明)
//   stat   : 変えるステータス (data/stats.js のキー。計算で決まる atk なども指定できる)
//   mult   : ステータスに掛ける倍率 (0 より大きい数)。1 より大きいと強化 (アイコンに上向きの矢印 ▲)、
//            1 より小さいと弱体 (下向きの矢印 ▼。例: 0.7 でそのステータスが 3 割下がる)
//   icon   : アイコンに書く 1 文字
//   color  : アイコンの地の色
// 倍率は装備なしのステータスにだけ掛かる (装備の分は変わらない)。続く行動回数は、かかったキャラ自身の行動で数える
// 同じものをもう一度かけると、残りの行動回数が長いほうになる (重ねがけはしない)
// =====================================================================

