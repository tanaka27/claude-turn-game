//
// 【術のダメージ計算式】
//   基礎ダメージ = 技の固定値(base) + 攻撃側int × 技の intRate (省略時は magic.intRate)
//   ダメージ = 基礎ダメージ × mdefScale / (mdefScale + 防御側mdef) × 乱数(1 ± variance)
//   ※四捨五入。最低 1。術は会心にならず、ミスもない
